import { useState } from 'react';
import { verifyClaim } from '../lib/api';
import type { HistoryItem, Settings, VerificationResult } from '../types/api';
import { ResultPanel } from '../components/ResultPanel';

interface VerifyProps {
  settings: Settings;
  onHistoryItem: (item: HistoryItem) => void;
}

export function Verify({ settings, onHistoryItem }: VerifyProps) {
  const [text, setText] = useState('');
  const [results, setResults] = useState<VerificationResult[]>([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function submit() {
    if (!text.trim()) {
      setError('Enter a claim before verifying.');
      return;
    }

    setLoading(true);
    setError(null);
    try {
      const nextResults = await verifyClaim(settings.apiBaseUrl, text.trim());
      setResults(nextResults);
      if (settings.saveHistory) {
        onHistoryItem({
          id: crypto.randomUUID(),
          claimText: text.trim(),
          createdAt: new Date().toISOString(),
          results: nextResults,
        });
      }
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Verification failed.');
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="grid gap-8 lg:grid-cols-[0.9fr_1.1fr]">
      <section className="rounded-[2rem] border border-slate-200 bg-white p-6 shadow-sm dark:border-white/10 dark:bg-white/5">
        <p className="text-sm uppercase tracking-[0.3em] text-slate-500 dark:text-slate-400">Verify</p>
        <h1 className="mt-3 text-4xl font-black tracking-tight">What should we check?</h1>
        <textarea
          className="mt-6 min-h-48 w-full resize-none rounded-3xl border border-slate-200 bg-slate-50 p-5 text-lg outline-none ring-sky-400/40 transition placeholder:text-slate-400 focus:ring-4 dark:border-white/10 dark:bg-ink/60"
          onChange={(event) => setText(event.target.value)}
          placeholder="Example: India banned AI systems."
          value={text}
        />
        {error ? <p className="mt-3 rounded-2xl bg-rose-500/10 p-3 text-sm font-semibold text-rose-500">{error}</p> : null}
        <button
          className="mt-5 inline-flex w-full items-center justify-center rounded-full bg-sky-400 px-6 py-4 font-black text-ink shadow-glow transition hover:-translate-y-0.5 disabled:cursor-not-allowed disabled:opacity-60"
          disabled={loading}
          onClick={submit}
          type="button"
        >
          {loading ? <span className="mr-2 h-4 w-4 animate-spin rounded-full border-2 border-ink/30 border-t-ink" /> : null}
          {loading ? 'Checking evidence…' : 'Verify claim'}
        </button>
        <p className="mt-4 text-sm text-slate-500 dark:text-slate-400">
          Connected to <code className="rounded bg-slate-100 px-1 dark:bg-white/10">{settings.apiBaseUrl}</code>
        </p>
      </section>
      <section className="min-h-[28rem]">
        {results.length ? (
          <div className="space-y-8">
            {results.map((result, index) => (
              <ResultPanel key={`${result.claim.text}-${index}`} result={result} />
            ))}
          </div>
        ) : (
          <div className="grid h-full place-items-center rounded-[2rem] border border-dashed border-slate-300 p-8 text-center dark:border-white/10">
            <div>
              <p className="text-5xl">🔎</p>
              <h2 className="mt-4 text-2xl font-black">Evidence results will appear here.</h2>
              <p className="mt-2 max-w-md text-slate-500 dark:text-slate-400">Submit a claim to see confidence, evidence cards, source links, and the explanation generated by the backend.</p>
            </div>
          </div>
        )}
      </section>
    </div>
  );
}
